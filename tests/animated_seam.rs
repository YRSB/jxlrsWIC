//! Headless animation tests for the multi-frame JPEG XL seam (`src/decoder_seam.rs`).
//!
//! The COM end-to-end layer in `tests/wic_com_e2e.rs` drives the registered DLL through WIC and
//! needs a registered decoder, so it cannot run without COM. These tests exercise the same
//! container through the pure-Rust [`jxlrs_wic::decoder_seam`] interface instead: the animated
//! fixture opens with a real frame count, every frame blits its own pixels, timing comes from the
//! scan, and corrupt input maps to [`DecodeError`](jxlrs_wic::decoder_seam::DecodeError) variants
//! the COM layer translates to `WINCODEC_ERR_BADIMAGE` / `WINCODEC_ERR_FRAMEMISSING`.
//!
//! Fixture: `tests/fixtures/anim_rgb_3f.jxl` — regenerated by `tests/fixtures/generate.py` from an
//! APNG with three 3x3 solid frames (red 100 ms, green 200 ms, blue 300 ms, loop forever).

use std::path::PathBuf;

use jxlrs_wic::decoder_seam::{DecodeError, JxlContainer, Rect, MAX_FRAMES};

/// Loads a committed fixture by name.
fn fixture(name: &str) -> Vec<u8> {
    let path = PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .join("tests")
        .join("fixtures")
        .join(name);
    std::fs::read(&path).unwrap_or_else(|err| panic!("missing fixture {}: {err}", path.display()))
}

/// Copies the whole frame into a tightly packed buffer of its own stride.
fn read_frame(container: &JxlContainer, index: usize) -> Vec<u8> {
    let frame = container.frame(index).expect("frame");
    let info = frame.info();
    let bytes_per_pixel = info.pixel_format.bytes_per_pixel();
    let stride = info.width as usize * bytes_per_pixel;
    let mut pixels = vec![0u8; stride * info.height as usize];
    frame
        .copy_pixels(None, stride, &mut pixels)
        .expect("copy_pixels");
    pixels
}

#[test]
fn animated_fixture_reports_three_frames() {
    let container = JxlContainer::open(&fixture("anim_rgb_3f.jxl")).expect("open animated fixture");
    assert_eq!(container.info().frame_count, 3);
    assert_eq!(container.frame_count(), 3);
}

#[test]
fn animated_fixture_carries_the_animation_header() {
    let container = JxlContainer::open(&fixture("anim_rgb_3f.jxl")).expect("open animated fixture");
    let animation = container.animation().expect("animation header");
    assert_eq!(animation.num_loops, 0);
    assert_eq!(animation.tps_numerator, 1000);
    assert_eq!(animation.tps_denominator, 1);
    assert!(!animation.have_timecodes);
    assert_eq!(animation.ticks_per_second(), 1000.0);
}

#[test]
fn animated_frame_timings_come_from_the_scan() {
    let container = JxlContainer::open(&fixture("anim_rgb_3f.jxl")).expect("open animated fixture");
    let expected = [(100, 100.0), (200, 200.0), (300, 300.0)];
    for (index, (ticks, ms)) in expected.into_iter().enumerate() {
        let frame = container.frame(index).expect("frame");
        assert_eq!(frame.index(), index);
        let timing = frame.timing();
        assert_eq!(timing.duration_ticks, ticks, "frame {index} duration ticks");
        assert_eq!(timing.duration_ms, ms, "frame {index} duration ms");
        assert_eq!(
            timing.is_last,
            index == 2,
            "only the last frame reports is_last"
        );
    }
}

#[test]
fn animated_frames_decode_distinct_pixels() {
    let container = JxlContainer::open(&fixture("anim_rgb_3f.jxl")).expect("open animated fixture");
    let first = read_frame(&container, 0);
    let second = read_frame(&container, 1);
    let third = read_frame(&container, 2);

    // The fixture encodes solid red, green, then blue frames; 32bppBGRA stores them B-G-R-A.
    assert_eq!(&first[..4], &[0, 0, 255, 255], "frame 0 is red");
    assert_eq!(&second[..4], &[0, 255, 0, 255], "frame 1 is green");
    assert_eq!(&third[..4], &[255, 0, 0, 255], "frame 2 is blue");
    assert_ne!(first, second);
    assert_ne!(second, third);
    assert_ne!(first, third);

    // Re-reading a frame serves the lazily Cached Raster, not a second decode.
    assert_eq!(read_frame(&container, 0), first);
}

#[test]
fn animated_frames_blits_honour_sub_rectangles() {
    let container = JxlContainer::open(&fixture("anim_rgb_3f.jxl")).expect("open animated fixture");
    let frame = container.frame(2).expect("frame");

    let mut pixel = vec![0u8; 4];
    frame
        .copy_pixels(Some(Rect::new(1, 1, 1, 1)), 4, &mut pixel)
        .expect("copy");
    assert_eq!(pixel, vec![255, 0, 0, 255], "frame 2 is solid blue");
}

#[test]
fn animated_container_rejects_frame_index_out_of_range() {
    let container = JxlContainer::open(&fixture("anim_rgb_3f.jxl")).expect("open animated fixture");
    assert_eq!(
        container.frame(3).err(),
        Some(DecodeError::FrameIndexOutOfRange {
            index: 3,
            frame_count: 3,
        }),
        "the first out-of-range index reports WINCODEC_ERR_FRAMEMISSING through to_hresult"
    );
    assert!(container.frame(MAX_FRAMES + 1).is_err());
}

#[test]
fn still_images_keep_single_frame_behaviour() {
    let container = JxlContainer::open(&fixture("srgb8_lossless.jxl")).expect("open still");
    assert_eq!(container.frame_count(), 1);
    assert_eq!(container.animation(), None);
    assert!(container.frame(1).is_err());

    // The still frame still blits the exact pixels the COM suite pins.
    let frame = container.frame(0).expect("frame");
    let info = frame.info();
    let stride = info.width as usize * info.pixel_format.bytes_per_pixel();
    let mut pixels = vec![0u8; stride * info.height as usize];
    frame
        .copy_pixels(None, stride, &mut pixels)
        .expect("copy_pixels");
    assert_eq!(&pixels[..4], &[255, 0, 0, 255], "opaque blue in BGRA order");
}

#[test]
fn corrupt_inputs_stay_decode_errors() {
    // Garbage with no signature, a bare signature with no bitstream, and a truncated prefix of
    // the animated fixture must all fail as data errors (COM maps these to
    // WINCODEC_ERR_BADIMAGE), never panic.
    assert!(matches!(
        JxlContainer::open(b"not a jpeg xl stream at all"),
        Err(DecodeError::InvalidBitstream(_))
    ));
    assert!(matches!(
        JxlContainer::open(&[0xFF, 0x0A]),
        Err(DecodeError::InvalidBitstream(_))
    ));
    let bytes = fixture("anim_rgb_3f.jxl");
    assert!(matches!(
        JxlContainer::open(&bytes[..bytes.len() / 2]),
        Err(DecodeError::InvalidBitstream(_))
    ));
}
